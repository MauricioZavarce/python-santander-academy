# Tuplas

tupla = (1, 2, 3, 4, 5)
print(tupla[0])  # Acessando o primeiro elemento da tupla
print(tupla[1])  # Acessando o segundo elemento da tupla
print(tupla[2])  # Acessando o terceiro elemento da tupla
print(tupla[3])  # Acessando o quarto elemento da tupla
print(tupla[4])  # Acessando o quinto elemento da tupla

print("A tupla é:", tupla)  # Imprimindo a tupla completa